import { isBrowserContext } from './runtime-context.js';

export const VALID_THEME_VALUES = new Set(['light', 'dark']);

export function normalizeStoredTheme(theme) {
  return VALID_THEME_VALUES.has(theme) ? theme : null;
}

export function renderThemeBootstrapScript() {
  return `// Generated by scripts/sync-theme-bootstrap.mjs; do not edit directly.
// Synchronous classic script for pre-paint theme restore in index.html and 404.html.
(function () {
  try {
    const theme = localStorage.getItem('theme');

    if (theme === 'light' || theme === 'dark') {
      document.documentElement.setAttribute('data-theme', theme);
    }
  } catch {
    // Ignore storage failures.
  }
})();
`;
}

export function bootstrapTheme({
  document = globalThis.document,
  storage = globalThis.localStorage
} = {}) {
  try {
    const theme = normalizeStoredTheme(storage.getItem('theme'));

    if (theme) {
      document.documentElement.setAttribute('data-theme', theme);
    }
  } catch {
    // Ignore storage failures.
  }
}

export function bootstrapThemeIfBrowser({ isBrowserContextImpl = isBrowserContext, ...options } = {}) {
  if (isBrowserContextImpl()) {
    bootstrapTheme(options);
  }
}
